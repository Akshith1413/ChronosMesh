"""Reproduce the ChronosMesh evaluation (blueprint §10).

    python examples/run_evaluation.py                 # full matrix (~10 min), writes docs/EVALUATION_RESULTS.md
    python examples/run_evaluation.py --quick         # small matrix for a smoke run
    python examples/run_evaluation.py --out results.json

Every number in the report comes from this script. Ground truth is produced by the simulator independently of
the reconstruction engine; ChronosMesh is compared with the arrival-order and wall-clock baselines and with a
declared-parents-only variant (what trace-propagation tools such as OpenTelemetry give you).
"""

from __future__ import annotations

import argparse
import json
import pathlib
import platform
import sys
import time

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from chronosmesh.evaluation import APPROACHES, run_experiment  # noqa: E402
from chronosmesh.simulator import ExperimentConfig  # noqa: E402

LABELS = {"arrival_order": "Arrival order", "wall_clock": "Wall clock", "declared_only": "Declared parents",
          "chronosmesh": "**ChronosMesh**"}


def scenarios(quick: bool):
    n, rep = (1500, 3) if quick else (5000, 5)
    base = dict(num_services=10, num_events=n, events_per_execution=20, repeats=rep, seed=100)
    return [
        ("S1 Out-of-order delivery (randomized, ≤500 ms)", dict(base, network_delay_ms=500)),
        ("S2 + clock drift (±200 ms per service)", dict(base, network_delay_ms=500, clock_drift_ms=200)),
        ("S3 Heavy-tailed latency + stragglers", dict(base, network_delay_ms=500, delivery_mode="heavily_delayed", clock_drift_ms=200)),
        ("S4 + 10 % duplicates", dict(base, network_delay_ms=500, duplicate_rate=0.10)),
        ("S5 + 5 % lost events", dict(base, network_delay_ms=500, missing_rate=0.05)),
        ("S6 Everything at once (delay, drift, 10 % dup, 5 % loss)", dict(base, network_delay_ms=500, delivery_mode="heavily_delayed",
                                                                         clock_drift_ms=200, duplicate_rate=0.10, missing_rate=0.05)),
        ("S7 10 % of events lose their vector clock", dict(base, network_delay_ms=500, metadata_loss_rate=0.10)),
        ("S8 30 % of events lose their vector clock", dict(base, network_delay_ms=500, metadata_loss_rate=0.30)),
        ("S9 Worker crashes ×3 with at-least-once redelivery", dict(base, network_delay_ms=500, duplicate_rate=0.05, worker_failures=3)),
        ("S10 Retry storm (5 % of operations retried 6×)", dict(base, network_delay_ms=500, retry_rate=0.05, retry_burst=6)),
    ]


def f(ci, digits=3):
    if ci["n"] <= 1:
        return f"{ci['mean']:.{digits}f}"
    return f"{ci['mean']:.{digits}f} ± {(ci['ci95_high'] - ci['ci95_low']) / 2:.{digits}f}"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--quick", action="store_true")
    ap.add_argument("--out", default=None, help="write the raw results as JSON")
    ap.add_argument("--report", default=str(ROOT / "docs" / "EVALUATION_RESULTS.md"))
    args = ap.parse_args()

    started = time.time()
    results = {"scenarios": [], "scale": [], "services": [], "regions": []}

    for title, params in scenarios(args.quick):
        print(f"[{time.time() - started:6.0f}s] {title}", flush=True)
        results["scenarios"].append({"title": title, **run_experiment(ExperimentConfig(**params))})

    sizes = (500, 1000, 2000) if args.quick else (1000, 5000, 10000, 20000)
    for n in sizes:
        print(f"[{time.time() - started:6.0f}s] scale n={n}", flush=True)
        cfg = ExperimentConfig(num_services=10, num_events=n, events_per_execution=20, network_delay_ms=500,
                               duplicate_rate=0.05, missing_rate=0.02, repeats=3, seed=200)
        results["scale"].append({"n": n, **run_experiment(cfg)})

    for s in ((4, 10) if args.quick else (4, 10, 25, 50)):
        print(f"[{time.time() - started:6.0f}s] services={s}", flush=True)
        cfg = ExperimentConfig(num_services=s, num_events=2000 if args.quick else 5000, events_per_execution=20,
                               network_delay_ms=500, duplicate_rate=0.05, missing_rate=0.02, repeats=3, seed=300)
        results["services"].append({"s": s, **run_experiment(cfg)})

    for x in ((0, 500) if args.quick else (0, 100, 500, 1000, 2000)):
        print(f"[{time.time() - started:6.0f}s] cross-region delay={x} ms", flush=True)
        cfg = ExperimentConfig(num_services=10, num_events=2000 if args.quick else 5000, events_per_execution=20,
                               network_delay_ms=50, cross_region_delay_ms=x, repeats=3, seed=400)
        results["regions"].append({"x": x, **run_experiment(cfg)})

    if args.out:
        pathlib.Path(args.out).write_text(json.dumps(results))

    md = ["# ChronosMesh — Evaluation Results", "",
          f"Generated by `examples/run_evaluation.py` on {time.strftime('%Y-%m-%d')} "
          f"({platform.python_version()}, {platform.machine()}, {platform.system()}); total {time.time() - started:.0f} s.", "",
          "Ground truth comes from the simulator's own bookkeeping, independent of the reconstruction engine. "
          "Cells are mean ± 95 % confidence half-width over the repeats (Student-t). "
          "**Edge F1** scores direct causal edges against the ground-truth transitive reduction of happens-before restricted to the "
          "events that were actually delivered, so ChronosMesh is not rewarded for edges that were lost with their events.", "",
          "Approaches: *Arrival order* and *Wall clock* chain consecutive events of an execution; *Declared parents* trusts "
          "`parent_event_ids` only; *ChronosMesh* combines vector clocks with verified declared parents.", ""]

    md += ["## 1. Fault scenarios", ""]
    for sc in results["scenarios"]:
        r0 = sc["runs"][0]
        s = sc["summary"]
        md += [f"### {sc['title']}", "",
               f"{sc['config']['num_events']} events in {r0['executions']} executions, {sc['config']['num_services']} services, "
               f"{len(sc['runs'])} repeats. Stream disorder: {r0['arrival_disorder']:.0%}; lost {r0['events_dropped']}, "
               f"duplicated {r0['events_duplicated']}, clock-metadata lost {r0['events_metadata_lost']} (first repeat).", "",
               "| Approach | Precision | Recall | **F1** | Event-ordering acc. | Late-edge recovery | Concurrent recall |",
               "|---|---|---|---|---|---|---|"]
        for a in APPROACHES:
            md.append(f"| {LABELS[a]} | {f(s['approaches'][a]['precision'])} | {f(s['approaches'][a]['recall'])} | "
                      f"{f(s['approaches'][a]['f1'])} | {f(s['ordering'][a])} | {f(s['late_event_recovery'][a])} | "
                      f"{f(s['concurrency'][a]['concurrent_recall'])} |")
        ft = r0["fault_tolerance"]
        extra = f"Recovery rate (F1 ≥ {s['recovery_f1_threshold']}): **{s['recovery_rate']:.0%}**."
        if s.get("duplicate_detection_rate"):
            extra += f" Duplicate detection rate: **{f(s['duplicate_detection_rate'])}**."
        if sc["title"].startswith("S10"):
            extra += f" Retry-storm anomalies flagged (first repeat): {r0['anomalies']['by_type'].get('RETRY_STORM', 0)}."
        if sc["config"]["worker_failures"]:
            extra += (f" Worker crashes injected/recovered: {ft['worker_crashes_injected']}/{ft['recoveries']}, "
                      f"{ft['redelivered_messages']} messages redelivered, graph identical to a crash-free run: "
                      f"**{'yes' if s['all_recoveries_consistent'] else 'NO'}**.")
        md += ["", extra, ""]

    md += ["## 2. Scale (10 services, 5 % duplicates, 2 % loss, 3 repeats)", "",
           "| Events | Executions | ChronosMesh F1 | Reconstruction time (s) | Throughput (events/s) | CPU (s) | Peak RSS (MB) |",
           "|---|---|---|---|---|---|---|"]
    for sc in results["scale"]:
        s, r0 = sc["summary"], sc["runs"][0]
        p = s["performance"]
        md.append(f"| {sc['n']:,} | {r0['executions']} | {f(s['approaches']['chronosmesh']['f1'])} | {f(p['reconstruction_seconds'], 2)} | "
                  f"{f(p['throughput_eps'], 0)} | {f(p['cpu_seconds'], 2)} | {p['peak_rss_mb']['mean']:.0f} |")

    md += ["", "## 3. Number of services (3 repeats)", "",
           "| Services | ChronosMesh F1 | Declared-parents F1 | Wall-clock F1 | Throughput (events/s) |", "|---|---|---|---|---|"]
    for sc in results["services"]:
        s = sc["summary"]
        md.append(f"| {sc['s']} | {f(s['approaches']['chronosmesh']['f1'])} | {f(s['approaches']['declared_only']['f1'])} | "
                  f"{f(s['approaches']['wall_clock']['f1'])} | {f(s['performance']['throughput_eps'], 0)} |")

    md += ["", "## 4. Cross-region delay impact (10 services, 50 ms base delay, 3 repeats)", "",
           "Extra delivery latency for services far from the ingestion region (Mumbai): GCP-Mumbai ×0.15, AWS-Singapore ×1.0, "
           "GCP-Singapore ×1.2 of the setting.", "",
           "| Cross-region delay | Arrival-order ordering acc. | Wall-clock ordering acc. | ChronosMesh ordering acc. | Arrival-order F1 | ChronosMesh F1 |",
           "|---|---|---|---|---|---|"]
    for sc in results["regions"]:
        s = sc["summary"]
        md.append(f"| {sc['x']} ms | {f(s['ordering']['arrival_order'])} | {f(s['ordering']['wall_clock'])} | {f(s['ordering']['chronosmesh'])} | "
                  f"{f(s['approaches']['arrival_order']['f1'])} | {f(s['approaches']['chronosmesh']['f1'])} |")

    md += ["", "## 5. Reading these results honestly", "",
           "* **Edge F1 is not the whole story for the baselines.** Arrival-order and wall-clock approaches output a *chain*; a chain can never equal "
           "a DAG, so even a perfectly ordered chain scores well below 1 on edge F1. *Event-ordering accuracy* (for truly causally ordered pairs, "
           "is the cause placed before the effect?) is therefore reported separately: it isolates ordering errors, showing arrival order "
           "failing under delivery disorder and the wall clock failing under clock drift, while logical clocks are immune to both.",
           "* *Late-edge recovery* is recall on the ground-truth edges whose cause arrived **after** its effect (the out-of-order case).",
           "* With **intact vector clocks** ChronosMesh's edge recovery and concurrency classification are exact by construction "
           "(vector clocks characterise happens-before); the experiment's value is showing what the *baselines* get wrong and how "
           "ChronosMesh behaves when the metadata or the delivery is degraded (S5–S9).",
           "* Concurrency accuracy is dominated by the class balance (most pairs inside a short business flow are ordered), so "
           "*concurrent recall* is the discriminating column: total-order approaches can never detect concurrency.",
           "* Metadata loss (S7/S8) is the realistic failure for ChronosMesh: events without a vector clock fall back to declared "
           "parents, so recall drops with the loss rate. This is a limitation of vector-clock methods, not hidden here.",
           "* Throughput/CPU are single-process Python figures from the machine named above, useful for relative comparison "
           "(scaling shape), not as an absolute capacity claim. Peak RSS is the process-wide high-water mark.",
           "* Dynamic service membership (clocks sized to a changing service set) is not evaluated; see the limitations in the "
           "completion report."]
    pathlib.Path(args.report).write_text("\n".join(md) + "\n")
    print("wrote", args.report)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
