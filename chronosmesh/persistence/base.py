"""Repository contract shared by the in-memory and AWS (DynamoDB + S3) backends."""

from __future__ import annotations

from typing import Any, Dict, List, Optional, Protocol

STATUSES = ("created", "queued", "running", "streaming", "succeeded", "failed")
TERMINAL_STATUSES = ("succeeded", "failed")


def blocked_by_terminal_state(current: dict, fields: dict) -> bool:
    """A finished execution must never be dragged back to an in-progress state by a late writer."""
    new = fields.get("status")
    return current.get("status") in TERMINAL_STATUSES and new is not None and new not in TERMINAL_STATUSES


class Repository(Protocol):
    """Everything the API and the worker persist.

    Records are plain JSON-serialisable dicts. ``put_segment`` is the durable log the worker
    writes *before* acknowledging a queue message (so a crash never loses an acknowledged event).
    """

    backend: str

    # executions / experiments
    def put_execution(self, record: Dict[str, Any]) -> None: ...
    def get_execution(self, execution_id: str) -> Optional[Dict[str, Any]]: ...
    def update_execution(self, execution_id: str, **fields: Any) -> Optional[Dict[str, Any]]: ...
    def list_executions(self, owner: Optional[str] = None, *, limit: int = 50,
                        parent_id: Optional[str] = None, include_children: bool = False) -> List[Dict[str, Any]]: ...

    # events
    def put_events(self, execution_id: str, events: List[Dict[str, Any]]) -> int: ...
    def get_events(self, execution_id: str, limit: Optional[int] = None) -> List[Dict[str, Any]]: ...

    # durable ingest log (one object per queue message)
    def put_segment(self, execution_id: str, seq: int, events: List[Dict[str, Any]]) -> None: ...
    def list_segments(self, execution_id: str) -> List[int]: ...
    def get_segment(self, execution_id: str, seq: int) -> List[Dict[str, Any]]: ...

    # derived artefacts
    def put_anomalies(self, execution_id: str, anomalies: List[Dict[str, Any]]) -> None: ...
    def get_anomalies(self, execution_id: str, limit: Optional[int] = None) -> List[Dict[str, Any]]: ...
    def put_graph(self, execution_id: str, graph: Dict[str, Any]) -> str: ...
    def get_graph(self, execution_id: str) -> Optional[Dict[str, Any]]: ...
    def put_blob(self, execution_id: str, name: str, payload: Any) -> str: ...
    def get_blob(self, execution_id: str, name: str) -> Optional[Any]: ...

    def health(self) -> Dict[str, Any]: ...
